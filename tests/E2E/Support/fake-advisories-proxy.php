<?php

/**
 * A tiny HTTPS "man in the middle" proxy that stands in for the advisory sources:
 * packagist.org (the 4.x drivers) and codeload.github.com (the deprecated "enlightn" driver).
 *
 * Why a proxy and not a mock: the e2e suite runs the package completely unmodified, and both
 * Laravel's HTTP client and enlightn/security-checker (which creates its own Guzzle client with a
 * hard-coded URL) honour the standard HTTPS_PROXY environment variable. The proxy terminates TLS
 * with a certificate signed by a throw-away CA that only the e2e PHP processes trust
 * (via `-d curl.cainfo=...`), so nothing on the machine itself is reconfigured.
 *
 * Usage: php fake-advisories-proxy.php <state-dir>
 *
 * The state directory holds:
 *   - ca.pem / server.pem / server.key  TLS material (generated by the test case)
 *   - <set>.zip / <set>.json            each fixture set as GitHub's archive and Packagist's feed
 *   - mode                              what to answer, re-read on every request:
 *                                         "serve:<set>"       200 with that fixture set
 *                                         "http-error:<code>" an HTTP error from the source
 *                                         "refuse"            refuse the CONNECT (network down)
 *   - port                              written by this script once it listens
 *   - requests.jsonl                    one line per request, for assertions
 */

const HOSTS = ['packagist.org', 'codeload.github.com'];

$stateDir = $argv[1] ?? null;

if ($stateDir === null || !is_dir($stateDir)) {
    fwrite(STDERR, "usage: php fake-advisories-proxy.php <state-dir>\n");
    exit(2);
}

$context = stream_context_create([
    'ssl' => [
        'local_cert' => $stateDir.'/server.pem',
        'local_pk' => $stateDir.'/server.key',
        'allow_self_signed' => false,
        'verify_peer' => false, // we are the server; clients do not present certificates
    ],
]);

// Port 0 lets the OS pick a free port, which avoids collisions when suites run in parallel.
$server = stream_socket_server('tcp://127.0.0.1:0', $errno, $errstr, STREAM_SERVER_BIND | STREAM_SERVER_LISTEN, $context);

if ($server === false) {
    fwrite(STDERR, "cannot listen: $errstr\n");
    exit(1);
}

$name = stream_socket_get_name($server, false);
file_put_contents($stateDir.'/port', substr($name, strrpos($name, ':') + 1));

while (true) {
    $connection = @stream_socket_accept($server, -1);

    if ($connection === false) {
        continue;
    }

    // A command makes its requests one after another, so serving connections one at a time
    // is enough and keeps this script free of any concurrency handling.
    handleConnection($connection, $stateDir);
    @fclose($connection);
}

function handleConnection($connection, string $stateDir): void
{
    stream_set_timeout($connection, 10);

    [$connectRequest] = readMessage($connection);

    if (!preg_match('#^CONNECT ([^\s:]+):(\d+) HTTP/1\.[01]#', $connectRequest, $m)) {
        logRequest($stateDir, ['type' => 'non-connect', 'head' => strtok($connectRequest, "\r\n")]);
        fwrite($connection, "HTTP/1.1 400 Bad Request\r\nContent-Length: 0\r\nConnection: close\r\n\r\n");

        return;
    }

    $host = $m[1];
    $mode = trim((string) @file_get_contents($stateDir.'/mode'));

    if ($mode === 'refuse' || !in_array($host, HOSTS, true)) {
        // Any other host means the package started talking to something new; refusing it makes
        // the test fail loudly instead of leaking onto the real network.
        logRequest($stateDir, ['type' => 'refused', 'host' => $host]);
        fwrite($connection, "HTTP/1.1 502 Bad Gateway\r\nContent-Length: 0\r\nConnection: close\r\n\r\n");

        return;
    }

    fwrite($connection, "HTTP/1.1 200 Connection Established\r\n\r\n");

    if (!@stream_socket_enable_crypto($connection, true, STREAM_CRYPTO_METHOD_TLS_SERVER)) {
        logRequest($stateDir, ['type' => 'tls-failed', 'host' => $host]);

        return;
    }

    [$head, $body] = readMessage($connection);
    $requestLine = strtok($head, "\r\n");
    $entry = ['type' => 'request', 'host' => $host, 'request' => $requestLine];

    // What a request reveals about the app matters (the default driver promises to send no
    // package names), so record the package list of per-package queries.
    if ($body !== '') {
        parse_str($body, $form);
        $entry['packages'] = $form['packages'] ?? null;
    }

    logRequest($stateDir, $entry);

    if (str_starts_with($mode, 'http-error:')) {
        $code = (int) substr($mode, strlen('http-error:'));
        respond($connection, $code, 'text/plain', "fake upstream error\n");

        return;
    }

    if (!str_starts_with($mode, 'serve:')) {
        respond($connection, 500, 'text/plain', "fake proxy has no mode configured\n");

        return;
    }

    $set = basename(substr($mode, strlen('serve:')));

    if ($host === 'codeload.github.com') {
        $archive = (string) file_get_contents($stateDir.'/'.$set.'.zip');

        // Always 200 (never 304), with a content-based ETag: switching fixture sets between
        // tests must never be masked by Enlightn's conditional-request cache.
        respond($connection, 200, 'application/zip', $archive, ['ETag: "'.sha1($archive).'"']);

        return;
    }

    respond($connection, 200, 'application/json', packagistResponse($stateDir.'/'.$set.'.json', $requestLine, $form ?? []));
}

/**
 * Answers like https://packagist.org/api/security-advisories/ does.
 */
function packagistResponse(string $feedFile, string $requestLine, array $form): string
{
    $feed = json_decode((string) file_get_contents($feedFile), true);

    if (str_starts_with($requestLine, 'GET /api/security-advisories/?updatedSince=')) {
        return json_encode($feed);
    }

    if (str_starts_with($requestLine, 'POST /api/security-advisories/ ') && is_array($form['packages'] ?? null)) {
        $requested = array_flip($form['packages']);

        // Like the real API, packages without advisories are simply left out.
        return json_encode(['advisories' => array_intersect_key($feed['advisories'], $requested)]);
    }

    // The real API answers 400 without updatedSince or packages; mimic it as an empty object
    // so a wrong request shows up as a test failure ("unexpected response").
    return json_encode(['error' => 'unsupported request: '.$requestLine]);
}

/**
 * Reads one HTTP message: the head, plus the body when a Content-Length says there is one.
 *
 * @return array{0: string, 1: string}
 */
function readMessage($connection): array
{
    $buffer = '';

    while (!str_contains($buffer, "\r\n\r\n")) {
        $chunk = fread($connection, 8192);

        if ($chunk === false || $chunk === '') {
            return [$buffer, ''];
        }

        $buffer .= $chunk;
    }

    [$head, $body] = explode("\r\n\r\n", $buffer, 2);
    $length = preg_match('/^Content-Length:\s*(\d+)/mi', $head, $m) ? (int) $m[1] : 0;

    while (strlen($body) < $length) {
        $chunk = fread($connection, $length - strlen($body));

        if ($chunk === false || $chunk === '') {
            break;
        }

        $body .= $chunk;
    }

    return [$head, $body];
}

function respond($connection, int $code, string $type, string $body, array $extraHeaders = []): void
{
    $headers = array_merge([
        "HTTP/1.1 $code Fake",
        'Content-Type: '.$type,
        'Content-Length: '.strlen($body),
        'Date: '.gmdate('D, d M Y H:i:s').' GMT',
        'Connection: close',
    ], $extraHeaders);

    fwrite($connection, implode("\r\n", $headers)."\r\n\r\n".$body);
}

function logRequest(string $stateDir, array $entry): void
{
    file_put_contents($stateDir.'/requests.jsonl', json_encode($entry)."\n", FILE_APPEND | LOCK_EX);
}
